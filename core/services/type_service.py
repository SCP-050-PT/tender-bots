    def normalize(self, raw_type: str) -> str:
        if not raw_type:
            return "unknown"
        return self.TYPE_ALIASES.get(raw_type.lower().strip(), raw_type.lower().strip())

    def resolve(
        self,
        tender_info: Dict[str, Any],
        documents_text: str,
        llm_classification: Optional[str] = None,
        llm_confidence: float = 0.0,
        tender_type_hint: Optional[str] = None,
    ) -> Tuple[str, str, str]:
        """
        Каскадное определение типа тендера (v7.2.0).

        Приоритет:
        1. Негативные ключевые слова → other
        2. Слабая модель (если confidence >= 0.5)
        3. Title heuristic
        4. Hint / текст / КТРУ
        """
        purchase_name = tender_info.get("purchase_name", "").lower()
        doc_text_lower = documents_text.lower() if documents_text else ""
        full_text = (purchase_name + " " + doc_text_lower).lower()

        # ============================================================
        # ШАГ 0: Негативные ключевые слова
        # ============================================================
        our_profile_markers = (
            "обучение",
            "охрана труда",
            "охране труда",
            "проверка знаний",
            "соут",
            "специальная оценка",
            "производственный контроль",
            "производственного контроля",
            "плк",
            "лабораторн",
            "оценка профессиональных рисков",
            "измерен",
            "вредных и (или) опасных",
            "вредных производственных",
            "физических фактор",
        )
        has_our_profile = any(m in full_text for m in our_profile_markers)

        # Негативы, которые часто встречаются в шаблонах наших ТЗ/договоров
        soft_negatives = (
            "экспертиза проектной документации",
            "техническое диагностирование",
            "диагностирование технических устройств",
        )

        for neg_kw in self.NEGATIVE_KEYWORDS:
            if neg_kw not in full_text:
                continue
            if has_our_profile and neg_kw in soft_negatives:
                logger.info(
                    f"[{self.VERSION}] Негатив '{neg_kw}' проигнорирован "
                    f"(есть маркеры ПЛК/СОУТ/ОТ)"
                )
                continue
            logger.warning(f"[{self.VERSION}] НЕГАТИВ: найдено '{neg_kw}' → other")
            return "other", "negative_keyword", "heuristic"

        # === Не ОПР: замеры воздуха / выбросы без маркеров ОПР ===
        air_or_emission = any(
            m in full_text
            for m in (
                "источников выбросов",
                "предельно-допустимых выбросов",
                "выбросов в атмосферу",
                "производственного экологического контроля",
                "физико-химических показателей источников",
            )
        )
        opr_markers = any(
            m in full_text
            for m in (
                "оценка профессиональных рисков",
                "профессиональных рисков",
                "идентификация опасностей",
                " о пр ",
                "опр ",
            )
        )
        if air_or_emission and not opr_markers:
            # Если есть наши can_measure по atmospheric_air — можно оставить как plk-like,
            # иначе other
            logger.warning(
                f"[{self.VERSION}] Выбросы/ПЭК без маркеров ОПР → other (проверить аккредитацию)"
            )
            return "other", "emission_not_opr", "heuristic"

        if any(
            m in full_text
            for m in (
                "сопротивления изоляции",
                "сопротивление изоляции",
                "замер сопротивления изоляции",
            )
        ):
            logger.warning(f"[{self.VERSION}] Сопротивление изоляции → other (не ОПР/ПЛК)")
            return "other", "electrical_not_our", "heuristic"

        # === Защита: замеры воздуха / рабочей зоны → PLK, а не OPR ===
        plk_air_markers = [
            "замеры воздуха",
            "замер воздуха",
            "воздуха рабочей зоны",
            "воздух рабочей зоны",
            "инструментальные замеры",
            "инструментальный замер",
            "контроль воздуха",
            "анализ воздуха рабочей",
        ]
        if any(m in full_text for m in plk_air_markers):
            # Если нет явных маркеров ОПР — это PLK
            opr_markers = ["оценка профессиональных рисков", "опр", "идентификация опасностей"]
            if not any(m in full_text for m in opr_markers):
                logger.info(f"[{self.VERSION}] Замеры воздуха/рабочей зоны → plk")
                return "plk", "air_measurement_guard", "heuristic"

        # ============================================================
        # ШАГ 1: Слабая модель (если есть и confidence достаточный)
        # ============================================================
        if llm_classification and llm_confidence >= 0.5:
            normalized = self.normalize(llm_classification)
            if normalized in ("other", "unknown"):
                logger.info(
                    f"[{self.VERSION}] Слабая модель сказала '{normalized}' "
                    f"(conf={llm_confidence:.2f}) → принимаем"
                )
                return normalized, "weak_model", "classify"

            # Если слабая модель дала конкретный тип — тоже принимаем
            # (даже если title думал иначе)
            logger.info(
                f"[{self.VERSION}] Тип из слабой модели: {normalized} "
                f"(conf={llm_confidence:.2f})"
            )
            return normalized, "weak_model", "classify"

        # ============================================================
        # ШАГ 2: Жёсткий приоритет Обучения
        # ============================================================
        education_markers_title = [
            "обучение",
            "подготовка кадров",
            "образовательных услуг",
            "повышение квалификации",
            "переподготовка",
            "курсы",
        ]
        education_markers_text = [
            "слушателей",
            "учебный план",
            "программа обучения",
            "удостоверение",
            "диплом",
            "проверка знаний",
        ]

        is_education_title = any(kw in purchase_name for kw in education_markers_title)
        is_education_text = any(
            kw in doc_text_lower[:2000] for kw in education_markers_text
        )

        if is_education_title or (
            is_education_text and "обучение" in doc_text_lower[:500]
        ):
            if not any(
                kw in purchase_name
                for kw in [
                    "специальная оценка",
                    "соут",
                    "производственный контроль",
                    "оценка профессиональных рисков",
                ]
            ):
                logger.info(f"[{self.VERSION}] HARD RULE: Маркеры обучения → education")
                return "education", "hard_rule_education", "heuristic"

        # ============================================================
        # ШАГ 3: Title heuristic (теперь ниже слабой модели)
        # ============================================================
        if purchase_name:
            if "combined" in self.TITLE_KEYWORDS:
                for kw in self.TITLE_KEYWORDS["combined"]:
                    if kw in purchase_name:
                        logger.info(
                            f"[{self.VERSION}] Тип из title: combined "
                            f"('{purchase_name[:60]}...')"
                        )
                        return "combined", "title_heuristic", "heuristic"

            for ttype, keywords in self.TITLE_KEYWORDS.items():
                if ttype == "combined":
                    continue
                if any(kw in purchase_name for kw in keywords):
                    logger.info(
                        f"[{self.VERSION}] Тип из title: {ttype} "
                        f"('{purchase_name[:60]}...')"
                    )
                    return ttype, "title_heuristic", "heuristic"

        # ============================================================
        # ШАГ 4: Hint из detailed_parser
        # ============================================================
        if tender_type_hint:
            normalized = self.normalize(tender_type_hint)

            if normalized == "opr" and (is_education_title or is_education_text):
                logger.warning(
                    f"[{self.VERSION}] Конфликт: Hint=OPR, но маркеры обучения → education"
                )
                return "education", "hint_override_education", "heuristic"

            if normalized == "opr" and any(
                kw in purchase_name for kw in ["лабораторн", "испытан", "замер"]
            ):
                logger.warning(
                    f"[{self.VERSION}] Конфликт: Hint=OPR, но лаборатория → plk"
                )
                return "plk", "hint_override_title", "heuristic"

            logger.info(f"[{self.VERSION}] Тип из detailed_parser hint: {normalized}")
            return normalized, "detailed_parser_hint", "hint"

        # ============================================================
        # ШАГ 5: Комбо по тексту
        # ============================================================
        has_sout_kw = any(
            kw in doc_text_lower
            for kw in ["специальная оценка", "соут", "оценка условий труда"]
        )
        has_opr_kw = any(
            kw in doc_text_lower
            for kw in [
                "оценка профессиональных рисков",
                "опр",
                "профессиональных рисков",
            ]
        )
        has_plk_kw = any(
            kw in doc_text_lower
            for kw in [
                "производственный контроль",
                "плк",
                "лабораторные исследования",
                "замеры",
            ]
        )

        combo_count = sum([has_sout_kw, has_opr_kw, has_plk_kw])
        if combo_count >= 2:
            logger.info(
                f"[{self.VERSION}] Обнаружен комбо-тендер по тексту ({combo_count} типа)"
            )
            return "combined", "text_heuristic_combo", "heuristic"

        # ============================================================
        # ШАГ 6: Защита от ложного ОПР
        # ============================================================
        if tender_type_hint == "opr":
            if any(
                kw in doc_text_lower
                for kw in [
                    "лабораторные исследования",
                    "испытания проб",
                    "сточной воды",
                ]
            ):
                logger.warning(
                    f"[{self.VERSION}] Ложный ОПР: признаки лаборатории → plk"
                )
                return "plk", "text_guard_opr", "heuristic"

            if (
                doc_text_lower.count("обучение") > 2
                and doc_text_lower.count("слушател") > 0
            ):
                logger.warning(
                    f"[{self.VERSION}] Ложный ОПР: признаки обучения → education"
                )
                return "education", "text_guard_opr_edu", "heuristic"

        # ============================================================
        # ШАГ 7: КТРУ-данные
        # ============================================================
        has_rm = bool(tender_info.get("rm_total") and tender_info["rm_total"] > 0)
        has_students = bool(
            tender_info.get("students_count") and tender_info["students_count"] > 0
        )
        has_points = bool(
            tender_info.get("points_count") and tender_info["points_count"] > 0
        )

        if (has_rm and has_points) or (has_rm and has_students):
            logger.info(f"[{self.VERSION}] Тип из КТРУ: combined")
            return "combined", "ktru", "data"

        if has_rm:
            logger.info(
                f"[{self.VERSION}] Тип из КТРУ: sout ({tender_info['rm_total']} РМ)"
            )
            return "sout", "ktru", "data"
        if has_points:
            logger.info(
                f"[{self.VERSION}] Тип из КТРУ: plk ({tender_info['points_count']} точек)"
            )
            return "plk", "ktru", "data"
        if has_students:
            logger.info(
                f"[{self.VERSION}] Тип из КТРУ: education ({tender_info['students_count']} слушателей)"
            )
            return "education", "ktru", "data"

        # ============================================================
        # ШАГ 8: Эвристика по тексту
        # ============================================================
        for ttype, keywords in self.KEYWORDS.items():
            if any(kw in doc_text_lower for kw in keywords):
                if ttype == "education" and (
                    "охрана труда" in doc_text_lower or "охране труда" in doc_text_lower
                ):
                    logger.info(f"[{self.VERSION}] Тип из текста: education (ОТ)")
                    return "education", "text_heuristic", "heuristic"

                logger.info(f"[{self.VERSION}] Тип из текста: {ttype}")
